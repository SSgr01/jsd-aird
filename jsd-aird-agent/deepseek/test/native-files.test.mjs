import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,mkdir,rm,symlink,writeFile,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createRequire} from 'node:module';
import EnterpriseFileSystem,{worldRoot} from '../../enterprise-plugin/src/filesystem.mjs';
import { LocalAttachmentStore } from '../../../vendor/deepseek-harness/packages/attachment/attachment-local/lib/index.js';
const require=createRequire(new URL('../../../vendor/deepseek-harness/packages/fs/fs-local/package.json',import.meta.url));
const {Context}=await import(pathToFileURL(require.resolve('@deepseek-ai/cordis')).href);

test('native filesystem keeps atomic stale guards and maps the sandbox world inside one owner',async t=>{
 const base=await mkdtemp(join(tmpdir(),'dsh-native-fs-')), root=join(base,'owner');await mkdir(root);
 const previous=process.env.JSD_DSH_EXECUTION_ROOT;process.env.JSD_DSH_EXECUTION_ROOT=root;
 const ctx=new Context(),fs=new EnterpriseFileSystem(ctx);
 t.after(async()=>{await ctx.fiber.dispose();if(previous===undefined)delete process.env.JSD_DSH_EXECUTION_ROOT;else process.env.JSD_DSH_EXECUTION_ROOT=previous;await rm(base,{recursive:true,force:true});});
 const target=await fs.resolve('note.txt');
 const first=await fs.writeText(target,'alpha',{kind:'createIfAbsent'});
 assert.equal(await fs.readText(target),'alpha');assert.equal(fs.processPath(target),worldRoot+'/note.txt');
 assert.equal((await fs.resolve(worldRoot+'/note.txt')).targetKey,target.targetKey);
 assert.equal((await fs.resolve(join(root,'note.txt'))).targetKey,target.targetKey);
 await assert.rejects(fs.resolve(root+'-other/note.txt'),error=>error.code==='FS_SANDBOX_DENIED');
 await fs.editText(target,{oldString:'alpha',newString:'beta'},{version:first.version});
 await assert.rejects(fs.editText(target,{oldString:'beta',newString:'lost'},{version:first.version}),error=>error.code==='FS_STALE_VERSION');
 await assert.rejects(fs.resolve('../outside'),error=>error.code==='FS_SANDBOX_DENIED');
 const other=join(base,'other');await mkdir(other);await writeFile(join(other,'secret.txt'),'other owner');
 await symlink(other,join(root,'escape'),process.platform==='win32'?'junction':'dir');
 await assert.rejects(fs.resolve('escape/secret.txt'),error=>error.code==='FS_SANDBOX_DENIED');
 assert.equal((await fs.listDir(await fs.resolve(root))).some(entry=>entry.name==='escape'),false);
 const attachments=new LocalAttachmentStore(ctx,{dshHome:join(base,'home')});
 const bytes=Buffer.from('native attachment bytes'), ref=await attachments.saveFile({name:'input.pdf',data:bytes});
 const originalPath=attachments.fileHostPath(ref);
 assert.equal(fs.processPathFromHostPath(originalPath),undefined);
 await fs.exposeAttachment(ref,bytes,root,originalPath);
 const exposed=fs.processPathFromHostPath(originalPath);
 assert.ok(exposed.startsWith(worldRoot+'/.dsh-attachments/'));
 assert.deepEqual(Buffer.from(await fs.readBytes(await fs.resolve(exposed))),bytes);
 assert.equal(fs.processPathFromHostPath(join(base,'home','private.txt')),undefined);
 const snapshot=await fs.snapshot(root);
 assert.deepEqual(Buffer.from(snapshot.find(file=>file.path.endsWith('/input.pdf')).base64,'base64'),bytes);
 await assert.rejects(fs.exposeAttachment(ref,Buffer.from('changed'),root,originalPath),/NATIVE_ATTACHMENT_MISMATCH/);
 await assert.rejects(fs.exposeAttachment(ref,bytes,other,originalPath),error=>error.code==='FS_SANDBOX_DENIED');
});

test('native Office references resolve relative to their virtual directory and remain read-only',async t=>{
 const base=await mkdtemp(join(tmpdir(),'dsh-office-fs-')),root=join(base,'owner'),resources=join(base,'skills');
 await mkdir(root);await mkdir(join(resources,'office-export-pdf'),{recursive:true});
 await mkdir(join(resources,'office','references'),{recursive:true});
 const reference=join(resources,'office','references','sidecar.md');await writeFile(reference,'native sidecar reference');
 const previous=[process.env.JSD_DSH_EXECUTION_ROOT,process.env.JSD_DSH_OFFICE_SKILLS];
 process.env.JSD_DSH_EXECUTION_ROOT=root;process.env.JSD_DSH_OFFICE_SKILLS=resources;
 const ctx=new Context(),fs=new EnterpriseFileSystem(ctx),denied=error=>error.code==='FS_SANDBOX_DENIED';
 t.after(async()=>{await ctx.fiber.dispose();
  for(const [i,name] of ['JSD_DSH_EXECUTION_ROOT','JSD_DSH_OFFICE_SKILLS'].entries())
   if(previous[i]===undefined)delete process.env[name];else process.env[name]=previous[i];
  await rm(base,{recursive:true,force:true});});
 const target=await fs.resolve('../office/references/sidecar.md',{cwd:'/opt/dsh-skills/office/office-export-pdf'});
 assert.equal(await fs.readText(target),'native sidecar reference');
 assert.equal(fs.processPath(target),'/opt/dsh-skills/office/office/references/sidecar.md');
 assert.equal((await fs.resolve(fs.processPath(target))).targetKey,target.targetKey);
 await assert.rejects(fs.writeText(target,'replacement',{kind:'overwrite'}),denied);
 await assert.rejects(fs.deleteFile(target),denied);
 await assert.rejects(fs.publish(String(target.targetKey),Buffer.from('replacement')),denied);
 await assert.rejects(fs.moveFile(target,await fs.resolve('copied.md')),denied);
 await assert.rejects(fs.moveFile(await fs.resolve('copied.md'),target),denied);
 await assert.rejects(fs.resolve('../../outside',{cwd:'/opt/dsh-skills/office/office-export-pdf'}),denied);
 await writeFile(join(base,'secret'),'not a skill');
 await symlink(base,join(resources,'escape'),process.platform==='win32'?'junction':'dir');
 await assert.rejects(fs.resolve('/opt/dsh-skills/office/escape/secret'),denied);
 assert.equal(await readFile(reference,'utf8'),'native sidecar reference');
});
