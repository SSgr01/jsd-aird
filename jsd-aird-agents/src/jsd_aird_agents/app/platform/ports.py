from typing import Any, Protocol

from jsd_aird_agents.contracts import IntentPlan, RunContext, ToolResult


class PackDomainGateway(Protocol):
    async def require_entry(self, ctx: RunContext, permission: str) -> None: ...
    async def require(self, ctx: RunContext, permission: str, scope_id: str) -> None: ...
    async def read(self, name: str, arguments: dict, ctx: RunContext) -> ToolResult: ...


class VerticalBusiness(Protocol):
    async def planning_context(self, ctx: RunContext, gateway: PackDomainGateway) -> dict: ...
    async def resolve(
        self, ctx: RunContext, plan: IntentPlan, gateway: PackDomainGateway
    ) -> tuple[str | None, dict | None]: ...


class MonitoringBusiness(Protocol):
    """Required only for packs registering monitoring profiles."""

    async def notification_recipients(
        self, owner, scope, observation, options, identity, gateway
    ) -> list[str]: ...
    async def validate_notification(self, conn, notice, recipient, now) -> None: ...


class ActionAuthority(Protocol):
    async def preview(self, ctx: RunContext, step_id: str, tool: str, arguments: dict) -> dict: ...
    async def get(self, action_id: str, principal: Any) -> dict: ...
    async def execute(self, ctx: RunContext, action_id: str) -> dict: ...
    async def reconcile(self) -> None: ...
    async def cancel_actions(self, run_id: str, conn: Any) -> None: ...
