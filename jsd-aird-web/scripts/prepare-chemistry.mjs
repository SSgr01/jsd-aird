import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';
const target = new URL('../public/chemistry/', import.meta.url);
await mkdir(target, { recursive: true });
const parser = new URL('../src/components/markdown/chemistry-input.ts', import.meta.url);
const javascript = stripTypeScriptTypes(await readFile(parser, 'utf8'));
await writeFile(new URL('input.js', target), '// Generated by scripts/prepare-chemistry.mjs.\n' + javascript.replaceAll('export function ', 'function ') + '\nglobalThis.chemistryList = chemistryList;\n');
for (const name of ['RDKit_minimal.js', 'RDKit_minimal.wasm']) {
  await copyFile(new URL('../node_modules/@rdkit/rdkit/dist/' + name, import.meta.url), new URL(name, target));
}
